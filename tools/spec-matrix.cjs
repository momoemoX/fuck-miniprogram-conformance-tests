// Generates and validates SPEC_MATRIX.md from fixtures/spec-matrix.json and fixtures/reference.js.
//
//   node tools/spec-matrix.cjs          # regenerate SPEC_MATRIX.md
//   node tools/spec-matrix.cjs --check  # fail on drift, orphan cases, or invalid clause metadata
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const matrixPath = path.join(root, "fixtures/spec-matrix.json");
const outputPath = path.join(root, "SPEC_MATRIX.md");
const reference = require(path.join(root, "fixtures/reference.js"));
const checkOnly = process.argv.includes("--check");

const matrix = JSON.parse(fs.readFileSync(matrixPath, "utf8"));
const refIds = new Set(Object.keys(reference));
const VALID_STATUS = new Set(["covered", "partial", "missing", "out-of-scope"]);
const VALID_PRIORITY = new Set(["P0", "P1", "P2"]);

const errors = [];
const seenClauseIds = new Set();
const explicitlyClaimed = new Set();

for (const domain of matrix.domains) {
  for (const clause of domain.clauses) {
    if (seenClauseIds.has(clause.id)) errors.push("Duplicate clause ID: " + clause.id);
    seenClauseIds.add(clause.id);
    if (!VALID_STATUS.has(clause.status)) errors.push(clause.id + ": invalid status " + clause.status);
    if (!VALID_PRIORITY.has(clause.priority)) errors.push(clause.id + ": invalid priority " + clause.priority);
    for (const id of clause.cases || []) {
      if (!refIds.has(id)) {
        errors.push(clause.id + ": references unknown case ID '" + id + "' (not in fixtures/reference.js)");
      }
      explicitlyClaimed.add(id);
    }
  }
}

// Resolve matched cases per clause (explicit cases + unclaimed prefix matches).
const allClaimed = new Set();
const resolvedByClause = new Map();

for (const domain of matrix.domains) {
  for (const clause of domain.clauses) {
    const matched = new Set(clause.cases || []);
    for (const prefix of clause.casePrefixes || []) {
      for (const id of refIds) {
        if (id.startsWith(prefix) && !explicitlyClaimed.has(id)) matched.add(id);
      }
    }
    const list = [...matched];
    resolvedByClause.set(clause.id, list);
    for (const id of list) allClaimed.add(id);

    const gaps = clause.gaps || [];
    if (clause.status === "covered") {
      if (list.length === 0) errors.push(clause.id + ": status is 'covered' but maps 0 cases");
      if (gaps.length > 0) errors.push(clause.id + ": status is 'covered' but still lists gaps");
    }
    if ((clause.status === "partial" || clause.status === "missing") && gaps.length === 0) {
      errors.push(clause.id + ": status is '" + clause.status + "' but lists no concrete gaps");
    }
    if (clause.status === "missing" && list.length > 0) {
      errors.push(clause.id + ": status is 'missing' but maps " + list.length + " cases (use 'partial' or 'covered')");
    }
  }
}

const orphans = [...refIds].filter((id) => !allClaimed.has(id));
if (orphans.length) {
  errors.push("Unmapped cases in fixtures/reference.js (" + orphans.length + "): " + orphans.join(", "));
}

if (errors.length) {
  console.error("Spec matrix validation failed (" + errors.length + " issues):");
  for (const error of errors) console.error("  - " + error);
  process.exit(1);
}

// Aggregate statistics
const counts = { total: 0, inScope: 0, covered: 0, partial: 0, missing: 0, outOfScope: 0, p0Total: 0, p0Covered: 0 };
const domainRows = [];
for (const domain of matrix.domains) {
  let covered = 0,
    partial = 0,
    missing = 0,
    outOfScope = 0,
    casesCount = 0;
  for (const clause of domain.clauses) {
    counts.total++;
    const n = resolvedByClause.get(clause.id).length;
    casesCount += n;
    if (clause.status === "covered") covered++;
    else if (clause.status === "partial") partial++;
    else if (clause.status === "missing") missing++;
    else if (clause.status === "out-of-scope") outOfScope++;
    if (clause.status !== "out-of-scope") {
      counts.inScope++;
      if (clause.priority === "P0") {
        counts.p0Total++;
        if (clause.status === "covered") counts.p0Covered++;
      }
    }
  }
  counts.covered += covered;
  counts.partial += partial;
  counts.missing += missing;
  counts.outOfScope += outOfScope;
  domainRows.push({
    id: domain.id,
    name: domain.name,
    clauses: domain.clauses.length,
    covered,
    partial,
    missing,
    outOfScope,
    casesCount,
  });
}

const badge = (status) => {
  if (status === "covered") return "COVERED";
  if (status === "partial") return "PARTIAL";
  if (status === "missing") return "MISSING";
  return "OUT-OF-SCOPE";
};

const lines = [];
lines.push("<!-- Generated by tools/spec-matrix.cjs from fixtures/spec-matrix.json. Do not edit by hand. -->");
lines.push("");
lines.push("# " + matrix.title + " (SDK " + matrix.targetSDK + ")");
lines.push("");
lines.push(
  "Machine-readable source: [`fixtures/spec-matrix.json`](fixtures/spec-matrix.json) · Generator & CI validator: [`tools/spec-matrix.cjs`](tools/spec-matrix.cjs) · Agent entry guide: [`AGENTS.md`](AGENTS.md)",
);
lines.push("");
lines.push("## Summary");
lines.push("");
lines.push(
  "- **Automatable in-scope clauses**: **" +
    counts.inScope +
    "** (" +
    counts.covered +
    " `COVERED`, " +
    counts.partial +
    " `PARTIAL`, " +
    counts.missing +
    " `MISSING`; plus " +
    counts.outOfScope +
    " `OUT-OF-SCOPE`)",
);
lines.push(
  "- **P0 clauses fully covered**: **" +
    counts.p0Covered +
    "/" +
    counts.p0Total +
    "** (" +
    Math.round((counts.p0Covered / counts.p0Total) * 100) +
    "%)",
);
lines.push(
  "- **Committed automated baseline cases mapped**: **" +
    allClaimed.size +
    "/" +
    refIds.size +
    "** (0 unmapped orphan cases)",
);
lines.push("");
lines.push("| Domain | Clauses | Covered | Partial | Missing | Out-of-scope | Mapped cases |");
lines.push("| --- | ---: | ---: | ---: | ---: | ---: | ---: |");
for (const row of domainRows) {
  lines.push(
    "| [" +
      row.name +
      "](#" +
      row.id +
      ") | " +
      row.clauses +
      " | " +
      row.covered +
      " | " +
      row.partial +
      " | " +
      row.missing +
      " | " +
      row.outOfScope +
      " | " +
      row.casesCount +
      " |",
  );
}
lines.push("");
lines.push("## Scope & Stopping Criterion (for Humans and AI Agents)");
lines.push("");
lines.push("**In scope (Mini Program-specific contracts):**");
for (const item of matrix.stoppingCriterion.inScope) lines.push("- " + item);
lines.push("");
lines.push("**Out of scope (do not pad test counts with these):**");
for (const item of matrix.stoppingCriterion.outOfScope) lines.push("- " + item);
lines.push("");
lines.push("**Clause completion rule:** " + matrix.stoppingCriterion.clauseCompletionRule);
lines.push("");
lines.push("## Priority Backlog (`MISSING` and `PARTIAL` Clauses)");
lines.push("");
lines.push("| Clause | Priority | Status | Mapped | Concrete Gaps to Close |");
lines.push("| --- | :---: | :---: | ---: | --- |");
const backlog = [];
for (const domain of matrix.domains) {
  for (const clause of domain.clauses) {
    if (clause.status === "missing" || clause.status === "partial") {
      backlog.push({ domain, clause });
    }
  }
}
const rank = { missing: 0, partial: 1 };
const prioRank = { P0: 0, P1: 1, P2: 2 };
backlog.sort((a, b) => prioRank[a.clause.priority] - prioRank[b.clause.priority] || rank[a.clause.status] - rank[b.clause.status]);
for (const { clause } of backlog) {
  const n = resolvedByClause.get(clause.id).length;
  lines.push(
    "| `" +
      clause.id +
      "` " +
      clause.title +
      " | " +
      clause.priority +
      " | `" +
      badge(clause.status) +
      "` | " +
      n +
      " | " +
      clause.gaps.join(" · ") +
      " |",
  );
}
lines.push("");
lines.push("## Domain Clauses");
lines.push("");
for (const domain of matrix.domains) {
  lines.push('<a id="' + domain.id + '"></a>');
  lines.push("### " + domain.name);
  lines.push("");
  lines.push("| ID | Priority | Status | Clause & Contract | Mapped Cases | Remaining Gaps |");
  lines.push("| --- | :---: | :---: | --- | ---: | --- |");
  for (const clause of domain.clauses) {
    const list = resolvedByClause.get(clause.id);
    const caseSummary =
      clause.casePrefixes && clause.casePrefixes.length
        ? list.length + " (`" + clause.casePrefixes.join("`, `") + "` + " + (clause.cases || []).length + " explicit)"
        : list.length
          ? list.length + " (" + list.slice(0, 4).map((id) => "`" + id + "`").join(", ") + (list.length > 4 ? ", …" : "") + ")"
          : "0";
    const gapText = clause.gaps && clause.gaps.length ? clause.gaps.join("; ") : "—";
    lines.push(
      "| `" +
        clause.id +
        "` | " +
        clause.priority +
        " | `" +
        badge(clause.status) +
        "` | **" +
        clause.title +
        "** — " +
        clause.contract +
        " | " +
        caseSummary +
        " | " +
        gapText +
        " |",
    );
  }
  lines.push("");
}

const rendered = lines.join("\n") + "\n";

if (checkOnly) {
  if (!fs.existsSync(outputPath)) {
    console.error("SPEC_MATRIX.md is missing. Run `node tools/spec-matrix.cjs`.");
    process.exit(1);
  }
  const current = fs.readFileSync(outputPath, "utf8");
  if (current !== rendered) {
    console.error("SPEC_MATRIX.md is out of date with fixtures/spec-matrix.json. Run `node tools/spec-matrix.cjs`.");
    process.exit(1);
  }
  console.log(
    "Verified SPEC_MATRIX.md: " +
      counts.inScope +
      " in-scope clauses (" +
      counts.covered +
      " covered, " +
      counts.partial +
      " partial, " +
      counts.missing +
      " missing), " +
      allClaimed.size +
      "/" +
      refIds.size +
      " cases mapped.",
  );
} else {
  fs.writeFileSync(outputPath, rendered);
  console.log(
    "Generated SPEC_MATRIX.md: " +
      counts.inScope +
      " in-scope clauses (" +
      counts.covered +
      " covered, " +
      counts.partial +
      " partial, " +
      counts.missing +
      " missing), " +
      allClaimed.size +
      "/" +
      refIds.size +
      " cases mapped.",
  );
}
