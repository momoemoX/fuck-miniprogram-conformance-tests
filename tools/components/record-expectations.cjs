// Records component expectations from baseline reports of the component cases.
//
//   node tools/components/record-expectations.cjs default.json serif.json monospace.json
//
// Each report comes from tools/devtools/run.cjs with the gallery font set to a different
// family (the suite page's `galleryFont` data). A property value is kept only when every
// run agrees. Render fields that differ between runs depend on font metrics, which vary
// across operating systems, and are not asserted.
const fs = require("fs");
const path = require("path");

const files = process.argv.slice(2);
if (files.length < 2) {
  console.error("Pass at least two reports recorded with different gallery fonts.");
  process.exit(2);
}

function results(file) {
  const report = JSON.parse(fs.readFileSync(file, "utf8"));
  const list = (report.report && report.report.results) || report.results || [];
  return new Map(list.map((result) => [result.id, result.actual]));
}

function parse(text) {
  try {
    return JSON.parse(text);
  } catch {
    return undefined;
  }
}

const runs = files.map(results);
const expectations = { defaults: {}, bound: {}, render: {}, states: {} };
const dropped = [];
for (const [id, text] of runs[0]) {
  const state = /^render\.state\.((.+?)\..+)$/.exec(id);
  if (state) {
    const [, key, tag] = state;
    const values = runs.map((run) => parse(run.get(id)));
    const defaults = runs.map((run) => parse(run.get("render." + tag)));
    if (values.some((value) => !value) || defaults.some((value) => !value)) {
      dropped.push(id + " (no object result)");
      continue;
    }
    const kept = {};
    for (const key of Object.keys(values[0])) {
      const first = JSON.stringify(values[0][key]);
      if (values.every((value) => JSON.stringify(value[key]) === first)) kept[key] = values[0][key];
    }
    // A state is a case only when a stable field differs from the default box in every run.
    const changes = Object.keys(kept).some((field) =>
      defaults.every((base) => JSON.stringify(base[field]) !== JSON.stringify(kept[field])),
    );
    if (changes) expectations.states[key] = kept;
    continue;
  }
  const match = /^(component\.defaults|component\.bound|render)\.(.+)$/.exec(id);
  if (!match) continue;
  const group = { "component.defaults": "defaults", "component.bound": "bound", render: "render" }[match[1]];
  const tag = match[2];
  const values = runs.map((run) => parse(run.get(id)));
  if (values.some((value) => !value || typeof value !== "object")) {
    dropped.push(id + " (no object result)");
    continue;
  }
  const kept = {};
  for (const key of Object.keys(values[0])) {
    const first = JSON.stringify(values[0][key]);
    if (values.every((value) => JSON.stringify(value[key]) === first)) kept[key] = values[0][key];
    else dropped.push(id + "." + key);
  }
  if (Object.keys(kept).length) expectations[group][tag] = kept;
}

const out = path.resolve(__dirname, "../../fixtures/component-expectations.js");
fs.writeFileSync(
  out,
  "// Component expectations recorded in the official developer-tool simulator with base\n" +
    "// library 3.7.12. Generated by tools/components/record-expectations.cjs; do not edit by hand.\n" +
    "module.exports = " +
    JSON.stringify(expectations, null, 2) +
    ";\n",
);
console.log(
  ["defaults", "bound", "render", "states"].map((group) => group + " " + Object.keys(expectations[group]).length).join(", ") +
    "; " +
    dropped.length +
    " fields not asserted",
);
for (const entry of dropped) console.log("  not asserted: " + entry);
