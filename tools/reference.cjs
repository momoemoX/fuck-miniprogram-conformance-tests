// Generates or verifies fixtures/reference.js from fixtures/devtools-3.7.12-observations.json.
//
//   node tools/reference.cjs          # regenerate fixtures/reference.js
//   node tools/reference.cjs --check  # fail if fixtures/reference.js diverges from observations
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const observationsPath = path.join(root, "fixtures/devtools-3.7.12-observations.json");
const referencePath = path.join(root, "fixtures/reference.js");
const checkOnly = process.argv.includes("--check");

const observations = JSON.parse(fs.readFileSync(observationsPath, "utf8"));
const results = observations.results || [];
if (!results.length) {
  console.error("No results found in " + observationsPath);
  process.exit(1);
}

const errors = [];
const expectedMap = {};
function matches(actual, expected) {
  if (actual === expected) return true;
  if (actual === null || expected === null || typeof actual !== "object" || typeof expected !== "object") return false;
  if (Array.isArray(actual) !== Array.isArray(expected)) return false;
  if (Array.isArray(expected) && actual.length !== expected.length) return false;
  const keys = Object.keys(expected);
  return (
    keys.length === Object.keys(actual).length &&
    keys.every((key) => Object.prototype.hasOwnProperty.call(actual, key) && matches(actual[key], expected[key]))
  );
}
for (const entry of results) {
  if (entry.status !== "PASS") {
    errors.push(entry.id + ": observation status is " + entry.status);
  }
  try {
    const exp = JSON.parse(entry.expected);
    const act = JSON.parse(entry.actual);
    if (!matches(act, exp)) {
      errors.push(entry.id + ": observation expected (" + entry.expected + ") !== actual (" + entry.actual + ")");
    }
    expectedMap[entry.id] = exp;
  } catch (error) {
    errors.push(entry.id + ": invalid JSON in observation (" + error.message + ")");
  }
}

if (errors.length) {
  console.error("Observation record validation failed (" + errors.length + " issues):");
  for (const error of errors) console.error("  - " + error);
  process.exit(1);
}

const generated =
  "// Expected values reproduced in the official developer-tool simulator with base library " +
  (observations.sdkVersion || "3.7.12") +
  ".\n" +
  "// Generated by tools/reference.cjs from fixtures/devtools-3.7.12-observations.json.\n" +
  "module.exports = " +
  JSON.stringify(expectedMap, null, 2) +
  ";\n";

if (checkOnly) {
  const committed = require(referencePath);
  const committedKeys = Object.keys(committed);
  const expectedKeys = Object.keys(expectedMap);
  const diffs = [];
  for (const key of expectedKeys) {
    if (!Object.prototype.hasOwnProperty.call(committed, key)) {
      diffs.push("missing in fixtures/reference.js: " + key);
    } else if (JSON.stringify(committed[key]) !== JSON.stringify(expectedMap[key])) {
      diffs.push("value mismatch for " + key);
    }
  }
  for (const key of committedKeys) {
    if (!Object.prototype.hasOwnProperty.call(expectedMap, key)) {
      diffs.push("extra in fixtures/reference.js: " + key);
    }
  }
  if (diffs.length) {
    console.error("fixtures/reference.js does not match observations (" + diffs.length + " diffs):");
    for (const diff of diffs) console.error("  - " + diff);
    console.error("Run `node tools/reference.cjs` to regenerate.");
    process.exit(1);
  }
  console.log("Verified fixtures/reference.js against " + expectedKeys.length + " observed expectations.");
} else {
  fs.writeFileSync(referencePath, generated);
  console.log("Wrote " + Object.keys(expectedMap).length + " expectations → " + referencePath);
}
